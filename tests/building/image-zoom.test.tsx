import assert from 'node:assert/strict';
import { test } from 'node:test';
import { act } from 'react';
import { useBuildingImageZoom } from '@/modules/building/model/use-building-image-zoom';
import { createBrowserEnvironment } from '../support/browser-environment';

function Harness({ onNavigate }: { onNavigate: (direction: number) => void }) {
  const zoom = useBuildingImageZoom({
    enabled: true,
    imageKey: 'image',
    next: () => onNavigate(1),
    prev: () => onNavigate(-1),
  });
  return (
    <section ref={zoom.viewportRef} aria-label="Image" {...zoom.handlers}>
      <span data-scale>{zoom.transform.scale}</span>
    </section>
  );
}

test('pointer gestures distinguish image swipes, double-taps, pinches and cancellations', async () => {
  const environment = createBrowserEnvironment();
  let changes = 0;
  try {
    await act(async () =>
      environment.root.render(
        <Harness
          onNavigate={(direction) => {
            changes += direction;
          }}
        />,
      ),
    );
    const viewport = environment.container.querySelector('section');
    assert.ok(viewport);
    viewport.getBoundingClientRect = () =>
      ({ left: 0, top: 0, width: 400, height: 300 }) as DOMRect;
    Object.assign(viewport, {
      setPointerCapture() {},
      hasPointerCapture() {
        return false;
      },
    });
    const pointer = async (type: string, x: number, y: number, id = 1) =>
      act(async () => {
        viewport.dispatchEvent(
          new environment.window.PointerEvent(type, {
            pointerId: id,
            pointerType: 'touch',
            button: 0,
            clientX: x,
            clientY: y,
            bubbles: true,
          }) as unknown as Event,
        );
      });
    const scale = () => Number(viewport.querySelector('[data-scale]')?.textContent);
    await pointer('pointerdown', 250, 100);
    await pointer('pointermove', 100, 100);
    await pointer('pointerup', 100, 100);
    assert.equal(changes, 1);
    // Vertical scrolling, system edge gestures and cancellations never switch images.
    await pointer('pointerdown', 200, 100);
    await pointer('pointermove', 200, 140);
    await pointer('pointerup', 100, 140);
    await pointer('pointerdown', 10, 100);
    await pointer('pointerup', 150, 100);
    await pointer('pointerdown', 200, 100);
    await pointer('pointercancel', 100, 100);
    assert.equal(changes, 1);
    // Pinch back to fit, lift a finger, then move: this is still a pinch, not a swipe.
    await pointer('pointerdown', 160, 100);
    await pointer('pointerdown', 240, 100, 2);
    await pointer('pointermove', 120, 100);
    await pointer('pointermove', 280, 100, 2);
    assert.equal(scale(), 2);
    await pointer('pointermove', 160, 100);
    await pointer('pointermove', 240, 100, 2);
    assert.equal(scale(), 1);
    await pointer('pointerup', 240, 100, 2);
    await pointer('pointermove', 60, 100);
    await pointer('pointerup', 60, 100);
    assert.equal(changes, 1);
    // A compatibility dblclick generated by touch must not undo double-tap zoom.
    await pointer('pointerdown', 200, 100);
    await pointer('pointerup', 200, 100);
    await pointer('pointerdown', 200, 100);
    await pointer('pointerup', 200, 100);
    assert.equal(scale(), 2);
    await act(async () =>
      viewport.dispatchEvent(
        new environment.window.MouseEvent('dblclick', { bubbles: true }) as unknown as Event,
      ),
    );
    assert.equal(scale(), 2);
    // Panning at a zoomed scale cannot advance the gallery.
    await pointer('pointerdown', 250, 100);
    await pointer('pointermove', 100, 100);
    await pointer('pointerup', 100, 100);
    assert.equal(changes, 1);
    const escapeEvent = new environment.window.KeyboardEvent('keydown', {
      key: 'Escape',
      bubbles: true,
      cancelable: true,
    });
    await act(async () => document.dispatchEvent(escapeEvent as unknown as Event));
    assert.equal(scale(), 1);
    assert.equal(escapeEvent.defaultPrevented, true);
  } finally {
    await environment.close();
  }
});
